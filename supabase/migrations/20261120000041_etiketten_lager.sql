-- Etiketten und Lager, Etappe 1 (20.11.2026). Spezifikation: docs/spezifikation-etiketten-packliste.md, Fassung 2.
-- Entscheide Dominik (20.11.2026): Produkt-Etikett ohne Anlass und Menülinie; Lager mit Seriennummer pro Beutel;
-- Ware bleibt über den Wechsel der Kollektion im Lager (eigener Stammsatz Produkt); Beutelzahl pro Spiel aufrunden;
-- Allergene «siehe Rezept», solange sie nicht verlässlich gepflegt sind; MHD ab Produktionsdatum (Migration 40).
--
-- Inhalt:
--  1. produkt und komponente.produkt_id
--  2. rezept.beutel_g, rezept_speichern
--  3. charge, lagereinheit, lagerbewegung, druckauftrag
--  4. bedarf_service_welle: welcher Service gehört zu welcher Welle einer Komponente
--  5. etikett_vorschlag, etikett_beutel
--  6. etiketten_erstellen
-- Noch nicht hier: Kisten, Packen, Scans (Etappe 4), ZPL und Druckdienst (Etappe 3), «Produkt einlagern» (Etappe 2).

-- 1. Produkt ------------------------------------------------------------------------------------------------------
-- Das, was etikettiert im Lager liegt, unabhängig von der Kollektion. Die Komponenten jeder Kollektion zeigen auf ihr Produkt.
create table public.produkt (
  id          uuid primary key default gen_random_uuid(),
  nr          integer generated by default as identity unique,
  name        text not null check (btrim(name) <> ''),
  kategorie   text references public.kategorie(code),
  erstellt_am timestamptz not null default now()
);
comment on table public.produkt is 'Produkt im Lager, über Kollektionen hinweg. nr ist die feste Produktnummer auf Etikett und im QR-Code (P0123).';
create index on public.produkt (kategorie);
alter table public.produkt enable row level security;
create policy pilot_angemeldet on public.produkt for all to authenticated using (true) with check (true);

alter table public.komponente add column produkt_id uuid references public.produkt(id) on delete restrict;
comment on column public.komponente.produkt_id is 'Produkt dieser Komponente. Leer = noch keinem Produkt zugeordnet; dann lassen sich keine Etiketten anlegen.';
create index on public.komponente (produkt_id);

-- Jede bestehende Komponente bekommt ihr eigenes Produkt (Namen sind nicht eindeutig, darum eins zu eins).
alter table public.produkt add column einrichtung_komponente uuid;
insert into public.produkt (name, kategorie, einrichtung_komponente)
select k.name, k.kategorie, k.id from public.komponente k order by k.kategorie, k.name, k.quelle_zeile;
update public.komponente k set produkt_id = p.id from public.produkt p where p.einrichtung_komponente = k.id;
alter table public.produkt drop column einrichtung_komponente;

-- 2. Füllmenge pro Beutel am Rezept -------------------------------------------------------------------------------
alter table public.rezept add column beutel_g numeric(12,2) check (beutel_g > 0);
comment on column public.rezept.beutel_g is 'Menge des fertigen Produkts in einem Beutel, in Gramm. Grundlage für die Anzahl Etiketten.';

-- Wie Migration 23, dazu im Kopf beutel_g.
create or replace function public.rezept_speichern(p_rezept uuid, p_geaendert_am timestamptz, p_daten jsonb)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  alt rezept%rowtype;
  v_id uuid := p_rezept;
  v_typ rezept_typ := (p_daten->>'typ')::rezept_typ;
  v_name text := nullif(btrim(p_daten->>'name'), '');
  v_slug text;
  v_basis text;
  v_n integer;
  neu timestamptz := clock_timestamp();
  g jsonb; z jsonb; s jsonb;
  gi integer := 0; zi integer; si integer;
  v_gid uuid; v_zid uuid; v_sid uuid;
  g_ids uuid[] := '{}'; z_ids uuid[] := '{}'; s_ids uuid[] := '{}';
  basis_anzahl integer := 0;
begin
  if v_name is null then
    raise exception 'Das Rezept braucht einen Namen.';
  end if;
  if v_typ is null then
    raise exception 'Der Typ (Gericht oder Komponente) fehlt.';
  end if;

  if v_id is null then
    -- Neues Rezept: freie Adresse suchen.
    v_basis := rezept_slug(v_name);
    v_slug := v_basis;
    v_n := 1;
    while exists (select 1 from rezept where slug = v_slug) loop
      v_n := v_n + 1;
      v_slug := v_basis || '-' || v_n;
    end loop;
    -- Basisportionen gleich mitgeben: ein Gericht ohne Basisportionen lässt die Tabelle nicht zu.
    insert into rezept (slug, typ, name, basis_portionen)
    values (v_slug, v_typ, v_name, (p_daten->>'basis_portionen')::integer) returning id into v_id;
  else
    select * into alt from rezept where id = v_id for update;
    if not found then
      raise exception 'Rezept nicht gefunden';
    end if;
    if alt.geaendert_am is distinct from p_geaendert_am then
      raise exception 'Das Rezept wurde inzwischen geändert. Bitte neu laden und die Änderung erneut eingeben.' using errcode = '40001';
    end if;
    v_slug := alt.slug;
    -- Typ wechseln nur, wenn keine Verknüpfung dagegen spricht.
    if v_typ = 'gericht' and alt.typ = 'komponente' and (
         exists (select 1 from rezept_komponente where komponente_id = v_id)
         or exists (select 1 from zutat where komponente_id = v_id)) then
      raise exception 'Typ nicht geändert: Das Rezept wird in einem Gericht als Komponente verwendet.';
    end if;
    if v_typ = 'komponente' and alt.typ = 'gericht' and exists (select 1 from rezept_komponente where gericht_id = v_id) then
      raise exception 'Typ nicht geändert: Das Gericht hat eigene Komponenten.';
    end if;
  end if;

  update rezept set
    name = v_name,
    untertitel = nullif(btrim(p_daten->>'untertitel'), ''),
    quelle = nullif(btrim(p_daten->>'quelle'), ''),
    typ = v_typ,
    kategorie = nullif(btrim(p_daten->>'kategorie'), ''),
    basis_portionen = (p_daten->>'basis_portionen')::integer,
    portion_g = (p_daten->>'portion_g')::numeric,
    ergibt_g = (p_daten->>'ergibt_g')::numeric,
    chargengroesse = nullif(btrim(p_daten->>'chargengroesse'), ''),
    besonderes = nullif(btrim(p_daten->>'besonderes'), ''),
    -- Eine Annahme kann nur an einem vorhandenen Wert hängen.
    portionen_annahme = coalesce((p_daten->>'portionen_annahme')::boolean, false) and (p_daten->>'basis_portionen') is not null,
    ergibt_annahme = coalesce((p_daten->>'ergibt_annahme')::boolean, false) and (p_daten->>'ergibt_g') is not null,
    -- Planung (Migration 23). Fehlt ein Schlüssel im Dokument, bleibt der gespeicherte Wert.
    gebinde_id = case when p_daten ? 'gebinde_id' then (p_daten->>'gebinde_id')::uuid else gebinde_id end,
    verpackung = case when p_daten ? 'verpackung' then nullif(btrim(p_daten->>'verpackung'), '') else verpackung end,
    fuellmenge_g = case when p_daten ? 'fuellmenge_g' then (p_daten->>'fuellmenge_g')::numeric else fuellmenge_g end,
    beutel_g = case when p_daten ? 'beutel_g' then (p_daten->>'beutel_g')::numeric else beutel_g end,
    service_min_pro_100 = case when p_daten ? 'service_min_pro_100' then (p_daten->>'service_min_pro_100')::numeric else service_min_pro_100 end,
    service_rolle = case when p_daten ? 'service_rolle' then nullif(btrim(p_daten->>'service_rolle'), '') else service_rolle end,
    geaendert_am = neu
  where id = v_id;

  for g in select value from jsonb_array_elements(coalesce(p_daten->'gruppen', '[]'::jsonb)) with ordinality order by ordinality loop
    gi := gi + 1;
    v_gid := (g->>'id')::uuid;
    if v_gid is null then
      insert into zutatengruppe (rezept_id, titel, reihenfolge)
      values (v_id, nullif(btrim(g->>'titel'), ''), gi) returning id into v_gid;
    else
      update zutatengruppe set titel = nullif(btrim(g->>'titel'), ''), reihenfolge = gi
      where id = v_gid and rezept_id = v_id;
      if not found then
        raise exception 'Nicht gespeichert: Eine Gruppe gehört nicht zu diesem Rezept.';
      end if;
    end if;
    if v_gid = any(g_ids) then
      raise exception 'Nicht gespeichert: Eine Gruppe kommt doppelt vor.';
    end if;
    g_ids := g_ids || v_gid;

    zi := 0;
    for z in select value from jsonb_array_elements(coalesce(g->'zutaten', '[]'::jsonb)) with ordinality order by ordinality loop
      zi := zi + 1;
      if nullif(btrim(z->>'bezeichnung'), '') is null then
        raise exception 'Nicht gespeichert: Eine Zutat hat keine Bezeichnung.';
      end if;
      if coalesce((z->>'ist_basis')::boolean, false) then
        basis_anzahl := basis_anzahl + 1;
        if (z->>'menge_g') is null then
          raise exception 'Basiszutat nicht gesetzt: Sie hat keine Menge in Gramm.';
        end if;
      end if;
      v_zid := (z->>'id')::uuid;
      if v_zid is null then
        insert into zutat (gruppe_id, bezeichnung, menge_g, ist_basis, annahme, notiz, reihenfolge)
        values (v_gid, btrim(z->>'bezeichnung'), (z->>'menge_g')::numeric, coalesce((z->>'ist_basis')::boolean, false),
                coalesce((z->>'annahme')::boolean, false) and (z->>'menge_g') is not null, nullif(btrim(z->>'notiz'), ''), zi)
        returning id into v_zid;
      else
        update zutat set
          gruppe_id = v_gid,
          bezeichnung = btrim(z->>'bezeichnung'),
          menge_g = (z->>'menge_g')::numeric,
          ist_basis = coalesce((z->>'ist_basis')::boolean, false),
          annahme = coalesce((z->>'annahme')::boolean, false) and (z->>'menge_g') is not null,
          notiz = nullif(btrim(z->>'notiz'), ''),
          reihenfolge = zi
        where id = v_zid and gruppe_id in (select id from zutatengruppe where rezept_id = v_id);
        if not found then
          raise exception 'Nicht gespeichert: Eine Zutat gehört nicht zu diesem Rezept.';
        end if;
      end if;
      if v_zid = any(z_ids) then
        raise exception 'Nicht gespeichert: Eine Zutat kommt doppelt vor.';
      end if;
      z_ids := z_ids || v_zid;
    end loop;

    si := 0;
    for s in select value from jsonb_array_elements(coalesce(g->'schritte', '[]'::jsonb)) with ordinality order by ordinality loop
      si := si + 1;
      if nullif(btrim(s->>'text'), '') is null then
        raise exception 'Nicht gespeichert: Ein Schritt hat keinen Text.';
      end if;
      v_sid := (s->>'id')::uuid;
      if v_sid is null then
        insert into schritt (gruppe_id, text, reihenfolge, geraet_id, temperatur_c, aktiv_min, unbeaufsichtigt_min, haccp, annahme,
                             ort, rolle, ruest_min, menge_pro_durchgang_g)
        values (v_gid, btrim(s->>'text'), si, (s->>'geraet_id')::uuid, (s->>'temperatur_c')::numeric,
                coalesce((s->>'aktiv_min')::numeric, 0), coalesce((s->>'unbeaufsichtigt_min')::numeric, 0),
                nullif(btrim(s->>'haccp'), ''), coalesce((s->>'annahme')::boolean, false),
                nullif(btrim(s->>'ort'), ''), nullif(btrim(s->>'rolle'), ''),
                coalesce((s->>'ruest_min')::numeric, 0), (s->>'menge_pro_durchgang_g')::numeric)
        returning id into v_sid;
      else
        update schritt set
          gruppe_id = v_gid,
          text = btrim(s->>'text'),
          reihenfolge = si,
          geraet_id = (s->>'geraet_id')::uuid,
          temperatur_c = (s->>'temperatur_c')::numeric,
          aktiv_min = coalesce((s->>'aktiv_min')::numeric, 0),
          unbeaufsichtigt_min = coalesce((s->>'unbeaufsichtigt_min')::numeric, 0),
          haccp = nullif(btrim(s->>'haccp'), ''),
          annahme = coalesce((s->>'annahme')::boolean, false),
          ort = case when s ? 'ort' then nullif(btrim(s->>'ort'), '') else ort end,
          rolle = case when s ? 'rolle' then nullif(btrim(s->>'rolle'), '') else rolle end,
          ruest_min = case when s ? 'ruest_min' then coalesce((s->>'ruest_min')::numeric, 0) else ruest_min end,
          menge_pro_durchgang_g = case when s ? 'menge_pro_durchgang_g' then (s->>'menge_pro_durchgang_g')::numeric else menge_pro_durchgang_g end
        where id = v_sid and gruppe_id in (select id from zutatengruppe where rezept_id = v_id);
        if not found then
          raise exception 'Nicht gespeichert: Ein Schritt gehört nicht zu diesem Rezept.';
        end if;
      end if;
      if v_sid = any(s_ids) then
        raise exception 'Nicht gespeichert: Ein Schritt kommt doppelt vor.';
      end if;
      s_ids := s_ids || v_sid;
    end loop;
  end loop;

  if basis_anzahl > 1 then
    raise exception 'Nicht gespeichert: Es gibt mehr als eine Basiszutat.';
  end if;

  -- Was im Dokument fehlt, wird gelöscht (zuerst Zutaten und Schritte, dann leere Gruppen).
  delete from zutat where gruppe_id in (select id from zutatengruppe where rezept_id = v_id) and id <> all(z_ids);
  delete from schritt where gruppe_id in (select id from zutatengruppe where rezept_id = v_id) and id <> all(s_ids);
  delete from zutatengruppe where rezept_id = v_id and id <> all(g_ids);

  update offener_punkt set erledigt = true
  where rezept_id = v_id
    and id in (select x::uuid from jsonb_array_elements_text(coalesce(p_daten->'erledigt', '[]'::jsonb)) x);

  return jsonb_build_object('id', v_id, 'slug', v_slug, 'geaendert_am', neu);
end
$$;

-- 3. Lager --------------------------------------------------------------------------------------------------------
-- Nichts vom Lager wird mitgelöscht: alle Fremdschlüssel sind restrict. Geschrieben wird nur über Funktionen
-- (security definer); angemeldete Benutzer dürfen diese Tabellen nur lesen.
create table public.charge (
  id               uuid primary key default gen_random_uuid(),
  produkt_id       uuid not null references public.produkt(id) on delete restrict,
  komponente_id    uuid not null references public.komponente(id) on delete restrict,
  -- Herkunft: Zeile der Checkliste. welle_nr ist eine Zahl wie in produktion_aufgabe (kein Fremdschlüssel auf die Welle,
  -- weil der Wellenplan beim Übernehmen neu angelegt wird). Beide leer = ohne Welle eingelagert (Etappe 2).
  saison_id        uuid references public.saison(id) on delete restrict,
  welle_nr         integer,
  produziert_am    date not null,
  haltbarkeit_tage integer,
  verbrauchen_bis  date not null,
  -- Produktions- oder Verbrauchsdatum von Hand gesetzt.
  datum_annahme    boolean not null default false,
  erstellt_am      timestamptz not null default now(),
  erstellt_von     uuid references auth.users(id) on delete set null,
  check (verbrauchen_bis >= produziert_am),
  unique nulls not distinct (komponente_id, saison_id, welle_nr, produziert_am)
);
comment on table public.charge is 'Ein Produkt aus einer Zeile der Checkliste an einem Produktionstag. Gehört zu keinem Anlass. Produktions- und Verbrauchsdatum sind beim Anlegen festgehalten.';
create index on public.charge (produkt_id);
create index on public.charge (saison_id);
create index on public.charge (erstellt_von);

create table public.lagereinheit (
  id           uuid primary key default gen_random_uuid(),
  charge_id    uuid not null references public.charge(id) on delete restrict,
  seriennummer text not null unique check (seriennummer ~ '^[A-HJKMNP-Z2-9]{8}$'),
  laufnummer   integer not null check (laufnummer > 0),
  menge        numeric(12,3) not null check (menge > 0),
  einheit      text not null check (einheit in ('kg', 'l', 'Stk')),
  zustand      text not null default 'im_lager' check (zustand in ('im_lager', 'in_kiste', 'verbraucht', 'entsorgt')),
  erstellt_am  timestamptz not null default now(),
  unique (charge_id, laufnummer)
);
comment on table public.lagereinheit is 'Ein etikettierter Beutel mit eigener Seriennummer (8 Zeichen ohne 0, O, 1, I, L). zustand ist massgebend; jede Änderung steht in lagerbewegung.';

create table public.lagerbewegung (
  id              uuid primary key default gen_random_uuid(),
  lagereinheit_id uuid not null references public.lagereinheit(id) on delete restrict,
  art             text not null check (art in ('eingang', 'eingepackt', 'ausgepackt', 'verbraucht', 'entsorgt', 'korrektur')),
  grund           text,
  zeitpunkt       timestamptz not null default now(),
  benutzer        uuid references auth.users(id) on delete set null
);
comment on table public.lagerbewegung is 'Verlauf pro Beutel: was, wann, wer. Wird nur von den Lager-Funktionen geschrieben.';
create index on public.lagerbewegung (lagereinheit_id);
create index on public.lagerbewegung (benutzer);

create table public.druckauftrag (
  id              uuid primary key default gen_random_uuid(),
  lagereinheit_id uuid not null references public.lagereinheit(id) on delete cascade,
  -- Der ZPL-Text entsteht mit Etappe 3 (Druck); bis dahin bleibt der Auftrag offen und leer.
  zpl             text,
  status          text not null default 'offen' check (status in ('offen', 'in_arbeit', 'gedruckt', 'fehler')),
  fehler          text,
  erstellt_am     timestamptz not null default now(),
  erstellt_von    uuid references auth.users(id) on delete set null,
  gedruckt_am     timestamptz
);
comment on table public.druckauftrag is 'Ein Etikett, das gedruckt werden soll. Etappe 1: bleibt offen, bis Druckdienst und ZPL (Etappe 3) stehen.';
create index on public.druckauftrag (lagereinheit_id);
create index on public.druckauftrag (erstellt_von);
create index on public.druckauftrag (status) where status in ('offen', 'in_arbeit');

alter table public.charge enable row level security;
alter table public.lagereinheit enable row level security;
alter table public.lagerbewegung enable row level security;
alter table public.druckauftrag enable row level security;
create policy lesen on public.charge for select to authenticated using (true);
create policy lesen on public.lagereinheit for select to authenticated using (true);
create policy lesen on public.lagerbewegung for select to authenticated using (true);
create policy lesen on public.druckauftrag for select to authenticated using (true);
revoke all on public.charge, public.lagereinheit, public.lagerbewegung, public.druckauftrag from anon;
revoke insert, update, delete, truncate on public.charge, public.lagereinheit, public.lagerbewegung, public.druckauftrag from authenticated;

-- 4. Service und Welle --------------------------------------------------------------------------------------------
-- Pro Service und Komponente die Welle, die ihn bedient. Gleiche Zuordnung wie in wellen_vorschlag (Migration 12):
-- ein Service gehört zur spätesten Welle, die vor seinem Datum produziert wird. Die Termine müssen genau gleich
-- gebildet werden wie dort, sonst weicht welle_nr von wellen_vorschlag.nr und produktion_aufgabe.welle_nr ab.
-- Wer wellen_vorschlag ändert, muss diese View mitziehen.
create view public.bedarf_service_welle with (security_invoker = true) as
with k as (
  select distinct b.saison_id, b.komponente_id, b.einheit_total, z.haltbarkeit_tage
  from service_komponente_bedarf b
  join komponente_zuteilung z on z.id = b.komponente_id
  where b.saison_id is not null and z.haltbarkeit_tage is not null
), hb as (
  select distinct saison_id, haltbarkeit_tage from k
), termine as (
  select d.saison_id, d.haltbarkeit_tage, d.produktion_am,
         (row_number() over (partition by d.saison_id, d.haltbarkeit_tage order by d.produktion_am))::int as nr
  from (
    select distinct hb.saison_id, hb.haltbarkeit_tage, w.produktion_am
    from hb
    cross join lateral wellen_termine(hb.saison_id, hb.haltbarkeit_tage) w
  ) d
)
select b.saison_id, b.komponente_id, b.einheit_total,
       (select max(t.nr) from termine t
        where t.saison_id = b.saison_id and t.haltbarkeit_tage = k.haltbarkeit_tage and t.produktion_am < b.datum) as welle_nr,
       b.service_id, b.service, b.reihenfolge, b.datum, b.menge, b.zeilen_ohne_menge
from service_komponente_bedarf b
join k on k.saison_id = b.saison_id and k.komponente_id = b.komponente_id and k.einheit_total = b.einheit_total;

comment on view public.bedarf_service_welle is 'Pro Service und Komponente (und Einheit) die Welle, die ihn bedient, mit der Menge des Service. Gleiche Zuordnung wie wellen_vorschlag. welle_nr leer: Service ohne Datum oder vor der ersten Welle.';

-- 5. Vorschlag und Etikett ----------------------------------------------------------------------------------------
-- Anzahl Beutel pro Zeile der Checkliste (Saison, Komponente, Welle) und Einheit. Ein Beutel geht ganz in ein Spiel,
-- darum wird pro Spiel aufgerundet und summiert (Entscheid Dominik). Liter gelten als Kilogramm (Annahme, wie in der Planung).
create view public.etikett_vorschlag with (security_invoker = true) as
with s0 as (
  -- Hat ein Service der Komponente kein Datum oder liegt er vor der ersten Welle, ist die Verteilung auf die Wellen
  -- unbekannt (wie in wellen_vorschlag): dann gibt es für keine Welle der Komponente einen Vorschlag.
  select b.*, (count(*) filter (where b.welle_nr is null)
               over (partition by b.saison_id, b.komponente_id, b.einheit_total))::int as ohne_welle
  from bedarf_service_welle b
), s as (
  select w.saison_id, w.komponente_id, w.welle_nr, w.einheit_total, w.service, w.reihenfolge, w.datum, w.menge, w.zeilen_ohne_menge, w.ohne_welle,
         r.beutel_g,
         case when w.ohne_welle = 0 and w.einheit_total in ('kg', 'l') and w.menge is not null and r.beutel_g is not null
              then ceil(w.menge * 1000 / r.beutel_g)::int end as beutel
  from s0 w
  join komponente k on k.id = w.komponente_id
  left join rezept r on r.id = k.rezept_id
  where w.welle_nr is not null
), g as (
  select s.saison_id, s.komponente_id, s.welle_nr, s.einheit_total, min(s.beutel_g) as beutel_g,
         count(*)::int as services,
         count(*) filter (where s.menge is null)::int as services_ohne_menge,
         max(s.ohne_welle) as services_ohne_welle,
         case when max(s.ohne_welle) = 0 and count(*) filter (where s.menge is null) = 0 then round(sum(s.menge), 3) end as menge_welle,
         case when count(*) filter (where s.beutel is null) = 0 then sum(s.beutel)::int end as beutel,
         string_agg(s.service || ': ' || coalesce(trim_scale(round(s.menge, 3))::text, '[Menge]') || ' ' || s.einheit_total
                    || coalesce(' ÷ ' || trim_scale(round(s.beutel_g / 1000, 3))::text || ' kg = ' || s.beutel || ' Beutel', ''),
                    ' + ' order by s.datum, s.reihenfolge) as je_service
  from s
  group by s.saison_id, s.komponente_id, s.welle_nr, s.einheit_total
), da as (
  -- Schon etikettiert für diese Zeile der Checkliste.
  select c.saison_id, c.komponente_id, c.welle_nr, e.einheit, count(*)::int as beutel, sum(e.menge) as menge
  from charge c
  join lagereinheit e on e.charge_id = c.id
  where e.zustand <> 'entsorgt'
  group by c.saison_id, c.komponente_id, c.welle_nr, e.einheit
)
select g.saison_id, g.komponente_id, g.welle_nr, g.einheit_total as einheit,
       g.menge_welle, g.beutel_g,
       case when g.einheit_total in ('kg', 'l') then round(g.beutel_g / 1000, 3) end as menge_pro_beutel,
       g.beutel,
       g.einheit_total = 'l' as liter_annahme,
       case
         when k.produkt_id is null then 'kein Produkt'
         when k.rezept_id is null then 'kein Rezept'
         when g.services_ohne_welle > 0 then 'Service ohne Datum oder vor der ersten Welle'
         when g.services_ohne_menge > 0 then 'Menge fehlt'
         when g.einheit_total = 'Stk' then 'Stück: Anzahl von Hand'
         when g.beutel_g is null then 'Füllmenge pro Beutel fehlt'
         else 'gerechnet'
       end as status,
       coalesce(da.beutel, 0) as beutel_vorhanden,
       -- Was nach den schon etikettierten Beuteln noch fehlt (nie unter 0).
       greatest(g.beutel - coalesce(da.beutel, 0), 0) as beutel_rest,
       coalesce(da.menge, 0) as menge_vorhanden,
       concat_ws('; ',
         case when g.services_ohne_welle > 0
              then g.services_ohne_welle || ' Service(s) ohne Datum oder vor der ersten Welle: Verteilung auf die Wellen unbekannt' end,
         g.je_service,
         case when g.beutel is not null and g.beutel_g is not null
              then 'zusammen ' || g.beutel || ' Beutel = ' || trim_scale(round(g.beutel * g.beutel_g / 1000, 3))::text || ' ' || g.einheit_total
                   || ' (Bedarf der Welle ' || coalesce(trim_scale(g.menge_welle)::text, '[Menge]') || ' ' || g.einheit_total || '; pro Spiel aufgerundet)' end,
         case when g.einheit_total = 'l' and g.beutel is not null then 'Annahme: 1 l = 1 kg' end,
         case when g.einheit_total = 'Stk' then 'Stück lassen sich nicht in Beutel umrechnen' end,
         case when g.beutel_g is null and g.einheit_total <> 'Stk' and k.rezept_id is not null then 'Füllmenge pro Beutel am Rezept erfassen' end
       ) as herleitung,
       -- Für die Vorschau des Etiketts, mit denselben Ausdrücken wie etikett_beutel.
       'P' || lpad(p.nr::text, 4, '0') as produkt_code, p.name as produkt, p.kategorie,
       k.lager_tk as tk,
       case when k.lager_tk then 'TK −18 °C' when k.lager_0_2 then '0–2 °C' when k.lager_trocken then 'Economat' end as lagerung,
       (select string_agg(ra.name, ', ' order by ra.reihenfolge)
        from regenerationsart ra where ra.code = any (k.regeneration)) as regeneration,
       'siehe Rezept'::text as allergene
from g
join komponente k on k.id = g.komponente_id
left join produkt p on p.id = k.produkt_id
left join da on da.saison_id = g.saison_id and da.komponente_id = g.komponente_id and da.welle_nr = g.welle_nr and da.einheit = g.einheit_total;

comment on view public.etikett_vorschlag is 'Vorschlag für die Anzahl Beutel pro Zeile der Checkliste (Saison, Komponente, Welle) und Einheit: pro Spiel Bedarf ÷ Füllmenge pro Beutel, aufgerundet, summiert. beutel_vorhanden: schon etikettiert.';

-- Alle Felder eines Beutel-Etiketts. Kein Anlass, keine Menülinie, keine Welle.
-- Lagerung und Regeneration kommen aus der Systemzuteilung der Komponente, aus der produziert wurde.
-- Allergene: die Tabellen dafür werden heute nicht gepflegt, darum immer «siehe Rezept» (nie eine unvollständige Liste).
create view public.etikett_beutel with (security_invoker = true) as
select e.id as lagereinheit_id, e.seriennummer, e.laufnummer, e.menge, e.einheit, e.zustand,
       (select count(*)::int from lagereinheit x where x.charge_id = c.id) as beutel_in_charge,
       c.id as charge_id, c.produziert_am, c.verbrauchen_bis, c.datum_annahme,
       p.id as produkt_id, p.nr as produkt_nr, 'P' || lpad(p.nr::text, 4, '0') as produkt_code, p.name as produkt, p.kategorie,
       k.lager_tk as tk,
       case when k.lager_tk then 'TK −18 °C' when k.lager_0_2 then '0–2 °C' when k.lager_trocken then 'Economat' end as lagerung,
       (select string_agg(ra.name, ', ' order by ra.reihenfolge)
        from regenerationsart ra where ra.code = any (k.regeneration)) as regeneration,
       'siehe Rezept'::text as allergene,
       'https://gamma.atoll-os.com/e/?p=' || p.nr || '&s=' || e.seriennummer as qr_text
from lagereinheit e
join charge c on c.id = e.charge_id
join produkt p on p.id = c.produkt_id
join komponente k on k.id = c.komponente_id;

comment on view public.etikett_beutel is 'Alle Felder des Beutel-Etiketts pro Lagereinheit. Web-Vorschau und (ab Etappe 3) ZPL lesen daraus. Ohne Anlass und Menülinie.';

-- 6. Etiketten anlegen --------------------------------------------------------------------------------------------
-- Legt für eine abgehakte Zeile der Checkliste Charge, Beutel, Lagerbewegung «Eingang» und Druckaufträge an.
-- Produktionsdatum: der Tag des Abhakens (produktion_aufgabe.produziert_am); von Hand nur auf einen früheren Tag.
-- Verbrauchsdatum: Produktionsdatum + Haltbarkeit der Systemzuteilung; fehlt sie, muss p_verbrauchen_bis gesetzt sein.
-- Ein weiterer Aufruf für dieselbe Zeile am selben Produktionstag hängt Beutel an die bestehende Charge an.
create function public.etiketten_erstellen(
  p_saison uuid, p_komponente uuid, p_welle integer, p_anzahl integer, p_menge numeric, p_einheit text,
  p_produziert_am date default null, p_verbrauchen_bis date default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  v_benutzer uuid := auth.uid();
  v_aufgabe produktion_aufgabe%rowtype;
  v_produkt uuid;
  v_tage integer;
  v_produziert date;
  v_bis date;
  v_annahme boolean := false;
  v_charge uuid;
  v_charge_bis date;
  v_start integer;
  v_einheit uuid;
  v_serie text;
  v_serien text[] := '{}';
  i integer;
  versuch integer;
begin
  if v_benutzer is null then
    raise exception 'Nicht angemeldet.' using errcode = '42501';
  end if;
  if p_anzahl is null or p_anzahl < 1 or p_anzahl > 500 then
    raise exception 'Anzahl Beutel: eine ganze Zahl von 1 bis 500.' using errcode = '22023';
  end if;
  if p_menge is null or p_menge <= 0 then
    raise exception 'Menge pro Beutel: eine Zahl über 0.' using errcode = '22023';
  end if;
  if p_einheit is null or p_einheit not in ('kg', 'l', 'Stk') then
    raise exception 'Einheit: kg, l oder Stk.' using errcode = '22023';
  end if;

  select * into v_aufgabe from produktion_aufgabe a
  where a.saison_id = p_saison and a.komponente_id = p_komponente and a.welle_nr = p_welle
  for update;
  if not found or v_aufgabe.erledigt_am is null then
    raise exception 'Etiketten gibt es erst, wenn die Zeile im Küchenpass abgehakt ist.' using errcode = '23514';
  end if;

  select k.produkt_id, z.haltbarkeit_tage into v_produkt, v_tage
  from komponente k join komponente_zuteilung z on z.id = k.id
  where k.id = p_komponente;
  if v_produkt is null then
    raise exception 'Diese Komponente ist noch keinem Produkt zugeordnet.' using errcode = '23514';
  end if;

  v_produziert := coalesce(v_aufgabe.produziert_am, (v_aufgabe.erledigt_am at time zone 'Europe/Zurich')::date);
  if p_produziert_am is not null and p_produziert_am <> v_produziert then
    if p_produziert_am > v_produziert then
      raise exception 'Das Produktionsdatum lässt sich nur auf einen früheren Tag korrigieren.' using errcode = '23514';
    end if;
    v_produziert := p_produziert_am;
    v_annahme := true;
  end if;

  select c.id, c.verbrauchen_bis into v_charge, v_charge_bis from charge c
  where c.komponente_id = p_komponente and c.saison_id = p_saison and c.welle_nr = p_welle and c.produziert_am = v_produziert;

  if v_charge is not null then
    -- Anhängen: das beim ersten Mal festgehaltene Verbrauchsdatum bleibt gültig, auch wenn die Systemzuteilung seither geändert hat.
    if p_verbrauchen_bis is not null and p_verbrauchen_bis <> v_charge_bis then
      raise exception 'Für diesen Produktionstag gibt es schon Beutel, verbrauchen bis %. Weitere Beutel bekommen dasselbe Datum.', to_char(v_charge_bis, 'DD.MM.YYYY') using errcode = '23514';
    end if;
    v_bis := v_charge_bis;
  else
    if v_tage is not null then
      v_bis := v_produziert + v_tage;
      if p_verbrauchen_bis is not null and p_verbrauchen_bis <> v_bis then
        if p_verbrauchen_bis > v_bis then
          raise exception 'Das Verbrauchsdatum lässt sich nur kürzen, nicht über die Haltbarkeit hinaus verlängern.' using errcode = '23514';
        end if;
        v_bis := p_verbrauchen_bis;
        v_annahme := true;
      end if;
    elsif p_verbrauchen_bis is not null then
      v_bis := p_verbrauchen_bis;
      v_annahme := true;
    else
      raise exception 'Die Haltbarkeit fehlt: bitte das Verbrauchsdatum von Hand setzen.' using errcode = '23514';
    end if;
    if v_bis < v_produziert then
      raise exception 'Das Verbrauchsdatum liegt vor dem Produktionsdatum.' using errcode = '23514';
    end if;
    insert into charge (produkt_id, komponente_id, saison_id, welle_nr, produziert_am, haltbarkeit_tage, verbrauchen_bis, datum_annahme, erstellt_von)
    values (v_produkt, p_komponente, p_saison, p_welle, v_produziert, v_tage, v_bis, v_annahme, v_benutzer)
    returning id into v_charge;
  end if;

  select coalesce(max(e.laufnummer), 0) into v_start from lagereinheit e where e.charge_id = v_charge;

  for i in 1..p_anzahl loop
    versuch := 0;
    loop
      versuch := versuch + 1;
      select string_agg(substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1), '') into v_serie from generate_series(1, 8);
      exit when not exists (select 1 from lagereinheit e where e.seriennummer = v_serie);
      if versuch > 20 then
        raise exception 'Keine freie Seriennummer gefunden, bitte nochmals versuchen.' using errcode = '40001';
      end if;
    end loop;
    insert into lagereinheit (charge_id, seriennummer, laufnummer, menge, einheit)
    values (v_charge, v_serie, v_start + i, p_menge, p_einheit)
    returning id into v_einheit;
    insert into lagerbewegung (lagereinheit_id, art, benutzer) values (v_einheit, 'eingang', v_benutzer);
    insert into druckauftrag (lagereinheit_id, erstellt_von) values (v_einheit, v_benutzer);
    v_serien := v_serien || v_serie;
  end loop;

  return jsonb_build_object('charge_id', v_charge, 'anzahl', p_anzahl, 'produziert_am', v_produziert,
                            'verbrauchen_bis', v_bis, 'seriennummern', to_jsonb(v_serien));
end
$$;

comment on function public.etiketten_erstellen(uuid, uuid, integer, integer, numeric, text, date, date) is 'Legt für eine abgehakte Zeile der Checkliste Charge, Beutel (im Lager), Lagerbewegung und Druckaufträge an. Einzige Stelle, die Beutel anlegt.';

revoke execute on function public.etiketten_erstellen(uuid, uuid, integer, integer, numeric, text, date, date) from public, anon;
grant execute on function public.etiketten_erstellen(uuid, uuid, integer, integer, numeric, text, date, date) to authenticated;
grant select on public.bedarf_service_welle, public.etikett_vorschlag, public.etikett_beutel to authenticated;
grant select on public.charge, public.lagereinheit, public.lagerbewegung, public.druckauftrag to authenticated;
